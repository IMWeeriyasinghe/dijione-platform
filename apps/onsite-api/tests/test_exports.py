def test_no_secret_or_internal_values(ready, db):
    wb = _wb(ready.get(f"/api/onsite/activity/export?date_from={DAY1}&date_to={DAY2}", headers=headers_for()))
    text = " ".join(str(v) for ws in wb for row in ws.iter_rows(values_only=True) for v in row if v is not None)
    for e in db.query(AttendanceEvent).all():
        assert e.record_hash not in text
    for word in ("hash", "secret", "token", "api_key", "password", "batch"):
        assert word not in text.lower()


