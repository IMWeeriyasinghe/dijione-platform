def test_large_exports_fail_safely(ready, monkeypatch):
    monkeypatch.setattr(attendance_export, "MAX_EXPORT_DAY_ROWS", 2)
    resp = ready.get(f"/api/onsite/activity/export?date_from={DAY1}&date_to={DAY2}", headers=headers_for("ONSITE_VIEWER"))
    assert resp.status_code == 413 and "Narrow the date range" in resp.json()["detail"]
    monkeypatch.setattr(attendance_export, "MAX_EXPORT_DAY_ROWS", 20_000)
    monkeypatch.setattr(attendance_export, "MAX_EXPORT_EVENTS", 3)
    resp = ready.get(f"/api/onsite/activity/export?date_from={DAY1}&date_to={DAY2}", headers=headers_for("ONSITE_VIEWER"))
    assert resp.status_code == 413
    # range cap still applies
    resp = ready.get("/api/onsite/activity/export?date_from=2026-01-01&date_to=2026-10-14",
                     headers=headers_for("ONSITE_VIEWER"))
    assert resp.status_code == 422


def test_formula_injection_neutralised(ready):
    wb = _wb(ready.get(f"/api/onsite/today/export?date={DAY1}", headers=headers_for("ONSITE_VIEWER")))
    ws = wb["Attendance Report"]
    cells = [c for row in ws.iter_rows() for c in row if isinstance(c.value, str)]
    assert all(c.data_type != "f" for c in cells)
    values = {c.value for c in cells}
    assert "'=HYPERLINK(\"http://x\")" in values and "'@Ops" in values
    assert not any(v.startswith(("=", "+", "@")) for v in values)


def test_neutral_terminology(ready):
    for path in EXPORTS:
        wb = _wb(ready.get(path, headers=headers_for("ONSITE_VIEWER")))
        text = " ".join(str(v) for ws in wb for row in ws.iter_rows(values_only=True) for v in row if v is not None)
        for word in ("Present", "Absent", "Late", "Early", "Worked"):
            assert not re.search(rf"{word}", text), (path, word)


def test_json_views_accept_the_same_filters(ready):
    v = headers_for("ONSITE_VIEWER")
    today = ready.get(f"/api/onsite/today?date={DAY1}&emp_code=0107", headers=v).json()
    assert [r["emp_code"] for r in today["items"]] == ["0107"]
    ex = ready.get(f"/api/onsite/exceptions?date_from={DAY1}&date_to={DAY2}&department=Finance", headers=v).json()
    assert {r["emp_code"] for r in ex["items"]} == {"0107"}
    # Unverified IDs are never listed to viewers, so the legacy UNMATCHED filter is always empty.
    emp = ready.get(f"/api/onsite/employees?date_from={DAY1}&date_to={DAY2}&identity_class=UNMATCHED", headers=v).json()
    assert emp["items"] == []
    emp = ready.get(f"/api/onsite/employees?date_from={DAY1}&date_to={DAY2}&identity_class=MATCHED_INACTIVE",
                    headers=v).json()
    assert {r["emp_code"] for r in emp["items"]} == {"103"}
