def _wb(resp):
    assert resp.status_code == 200, resp.text
    return load_workbook(io.BytesIO(resp.content))


_SECOND_HEADER = {"Team Member Name", "Local Time", "BHR Employee ID", "Value", "Attendance Events"}


def _table(ws):
    """Header + data rows of the report table (below the filter block)."""
    rows = [list(r) for r in ws.iter_rows(values_only=True)]
    start = next(i for i, r in enumerate(rows) if len(r) > 1 and r[1] in _SECOND_HEADER)
    header = rows[start]
    data = [r for r in rows[start + 1:] if any(v is not None for v in r)]
    return header, data


def _codes(resp, sheet="Attendance Report"):
    header, data = _table(_wb(resp)[sheet])
    col = header.index("ZKBioTime ID(s)" if "ZKBioTime ID(s)" in header else "ZKBioTime ID")
    return {c for r in data if r[col] for c in str(r[col]).split(", ")}  # empty-report message row has none


def test_valid_xlsx_mime_filename_and_metadata(ready):
    resp = ready.get(f"/api/onsite/today/export?date={DAY1}&department=Finance", headers=headers_for("ONSITE_VIEWER"))
    wb = _wb(resp)
    assert resp.headers["content-type"] == XLSX
    assert resp.headers["content-disposition"] == f'attachment; filename="Diji-Onsite_Attendance_Finance_{DAY1}.xlsx"'
    assert wb.sheetnames == ["Attendance Report", "Event Detail", "Summary"]
    ws = wb["Attendance Report"]
    assert (ws["A1"].value, ws["A2"].value, ws["A3"].value) == ("DijiOne", "Diji On-site", "Attendance Activity Report")
    meta = {r[0]: r[1] for r in ws.iter_rows(min_row=5, max_row=16, max_col=2, values_only=True) if r[0]}
    assert meta["Site"] == "DEV Site (Colombo)" and meta["Date"] == DAY1 and meta["Department"] == "Finance"
    assert meta["Generated by"] and meta["Generated at"]
    header, _ = _table(ws)
    assert header == ["Date", "Team Member Name", "BHR Employee ID", "EMP Number", "ZKBioTime ID(s)",
                      "Department", "Employment Status", "First Activity", "Latest Activity", "Punch Count",
                      "Activity Span (minutes)", "Terminal(s)", "Mapping Status", "Review Flags"]
    assert ws.freeze_panes and ws.tables  # frozen header + Excel table (AutoFilter, banding)


