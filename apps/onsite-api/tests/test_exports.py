def test_exception_filter(ready):
    # UNMATCHED_CODE no longer occurs in viewer exports: unmapped IDs are excluded entirely.
    resp = ready.get(f"/api/onsite/exceptions/export?date_from={DAY1}&date_to={DAY2}&flag=UNMATCHED_CODE",
                     headers=headers_for("ONSITE_VIEWER"))
    assert _codes(resp, "Exception Report") == set()
    resp = ready.get(f"/api/onsite/exceptions/export?date_from={DAY1}&date_to={DAY2}&flag=INACTIVE_EMPLOYEE_ACTIVITY",
                     headers=headers_for("ONSITE_VIEWER"))
    wb = _wb(resp)
    header, data = _table(wb["Exception Report"])
    assert {r[header.index("ZKBioTime ID(s)")] for r in data} == {"103"}
    assert all("Inactive team member activity" in r[header.index("Review Flags")] for r in data)
    assert "Review Reasons" in header
    all_ex = _wb(ready.get(f"/api/onsite/exceptions/export?date_from={DAY1}&date_to={DAY2}",
                           headers=headers_for("ONSITE_VIEWER")))
    h2, rows = _table(all_ex["Exception Report"])
    assert rows and all(r[h2.index("Review Flags")] for r in rows)  # only flagged rows
    summary = {r[0]: r[1] for r in all_ex["Summary"].iter_rows(values_only=True) if r[0]}
    assert summary["Unmapped punches excluded (see Identity Management)"] == 3  # 999, 105, TEST-AZURE-001


