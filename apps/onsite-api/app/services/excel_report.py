"""Branded .xlsx rendering for Diji On-site reports (openpyxl, server-side).

Pure presentation: callers hand over already-authorized, already-filtered
rows. Every text cell is escaped against spreadsheet formula injection."""

from __future__ import annotations

import io
from dataclasses import dataclass, field
from datetime import date, datetime, time

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.table import Table, TableStyleInfo

# Brand values mirror packages/design-system/src/globals.css (--dt-orange,
# --dt-cream, text tokens). Kept here once; nothing else hardcodes colours.
BRAND = {"primary": "F1592A", "tint": "FFEFD5", "text": "1F2937", "muted": "6B7280"}
TABLE_STYLE = "TableStyleMedium3"  # banded rows in the theme's orange accent

XLSX_MEDIA_TYPE = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
_FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r", "\n")
_FORMATS = {"date": "yyyy-mm-dd", "time": "hh:mm:ss", "datetime": "yyyy-mm-dd hh:mm", "int": "#,##0"}


def safe_text(value: str) -> str:
    """Neutralise values Excel would evaluate as a formula (OWASP CSV/Excel
    injection guidance): prefix with an apostrophe so they stay literal text."""
    return "'" + value if value.startswith(_FORMULA_PREFIXES) else value


@dataclass
class Column:
    header: str
    width: int = 16
    fmt: str | None = None  # date | time | datetime | int
    wrap: bool = False


@dataclass
class Sheet:
    title: str
    columns: list[Column]
    rows: list[list]
    empty_message: str = "No records match the selected filters."


@dataclass
class ReportMeta:
    title: str
    generated_by: str
    filters: list[tuple[str, str]] = field(default_factory=list)
    generated_at: datetime = field(default_factory=datetime.now)


def _cell_value(value):
    if isinstance(value, str):
        return safe_text(value)
    if value is None or isinstance(value, (int, float, bool, date, datetime, time)):
        return value
    return safe_text(str(value))


def _write_sheet(ws, sheet: Sheet, meta: ReportMeta, table_index: int) -> None:
    ws.sheet_view.showGridLines = False
    ws["A1"] = "DijiOne"
    ws["A1"].font = Font(size=10, bold=True, color=BRAND["muted"])
    ws["A2"] = "Diji On-site"
    ws["A2"].font = Font(size=12, bold=True, color=BRAND["primary"])
    ws["A3"] = meta.title if table_index == 1 else f"{meta.title} — {sheet.title}"
    ws["A3"].font = Font(size=16, bold=True, color=BRAND["text"])

    row = 5
    info = [*meta.filters, ("Generated at", meta.generated_at.strftime("%Y-%m-%d %H:%M")),
            ("Generated by", meta.generated_by)]
    for label, value in info:
        ws.cell(row=row, column=1, value=label).font = Font(bold=True, color=BRAND["muted"])
        ws.cell(row=row, column=2, value=_cell_value(value))
        row += 1
    row += 1

    header_row = row
    header_fill = PatternFill("solid", start_color=BRAND["primary"])
    for i, col in enumerate(sheet.columns, start=1):
        c = ws.cell(row=header_row, column=i, value=col.header)
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = header_fill
        c.alignment = Alignment(vertical="center", wrap_text=True)
        ws.column_dimensions[get_column_letter(i)].width = max(col.width, 14 if i <= 2 else 0)

    if not sheet.rows:
        ws.cell(row=header_row + 1, column=1, value=sheet.empty_message).font = Font(italic=True, color=BRAND["muted"])
    for r_off, values in enumerate(sheet.rows, start=1):
        for i, (col, value) in enumerate(zip(sheet.columns, values, strict=True), start=1):
            c = ws.cell(row=header_row + r_off, column=i, value=_cell_value(value))
            if col.fmt:
                c.number_format = _FORMATS[col.fmt]
            if col.wrap:
                c.alignment = Alignment(wrap_text=True, vertical="top")

    last_col = get_column_letter(len(sheet.columns))
    if sheet.rows:  # Excel tables need at least one data row
        table = Table(displayName=f"OnsiteTable{table_index}",
                      ref=f"A{header_row}:{last_col}{header_row + len(sheet.rows)}")
        table.tableStyleInfo = TableStyleInfo(name=TABLE_STYLE, showRowStripes=True)
        ws.add_table(table)
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)

    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.print_title_rows = f"{header_row}:{header_row}"
    ws.oddFooter.center.text = "Diji On-site · &P / &N"


def build_workbook(meta: ReportMeta, sheets: list[Sheet]) -> bytes:
    wb = Workbook()
    wb.remove(wb.active)
    for i, sheet in enumerate(sheets, start=1):
        _write_sheet(wb.create_sheet(sheet.title[:31]), sheet, meta, i)
    wb.properties.title = meta.title
    wb.properties.creator = "Diji On-site"
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
