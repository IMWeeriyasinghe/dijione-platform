"""Real Microsoft Graph transport — Managed Identity only, never a client
secret. Authenticates via ``azure.identity.DefaultAzureCredential`` (ambient
Managed Identity inside an Azure Container App; no ambient identity on a
developer machine, so this transport is only ever exercised in a deployed
environment — local/CI always use NullMailTransport).

Uses a single ``POST /users/{mailbox}/sendMail`` call, requiring only the
``Mail.Send`` permission — never the create-draft-then-send sequence, which
would need the broader ``Mail.ReadWrite``. ``sendMail`` returns
``202 Accepted`` with an empty body on success, so there is no Graph-native
message id to capture; the caller-supplied ``correlation_id`` (generated by
MailClient before this transport is ever invoked) is the only business
identifier this design depends on.
"""

from __future__ import annotations

import time

import httpx
from azure.identity import DefaultAzureCredential

from mail_client_py.transport import MailOutcome, MailResult, MailTransport

_GRAPH_SCOPE = "https://graph.microsoft.com/.default"
# Refresh a little before actual expiry to avoid racing a request against it.
_TOKEN_EXPIRY_SAFETY_MARGIN_SECONDS = 60


class GraphTransportNotConfiguredError(Exception):
    """Raised when GraphMailTransport is constructed without a sender mailbox."""


class GraphMailTransport(MailTransport):
    def __init__(self, *, sender_mailbox: str, base_url: str = "https://graph.microsoft.com/v1.0"):
        if not sender_mailbox:
            raise GraphTransportNotConfiguredError(
                "GraphMailTransport requires a sender_mailbox — the mailbox this transport always "
                "sends as. There is no per-call sender override (sender sanitization is structural)."
            )
        self._sender_mailbox = sender_mailbox
        self._base_url = base_url
        self._credential = DefaultAzureCredential()
        self._cached_token: str | None = None
        self._token_expires_at: float = 0.0

    def _get_access_token(self) -> str:
        now = time.monotonic()
        if self._cached_token and now < self._token_expires_at:
            return self._cached_token

        token = self._credential.get_token(_GRAPH_SCOPE)
        self._cached_token = token.token
        # token.expires_on is an absolute epoch timestamp; convert to a
        # monotonic-clock deadline so a system clock change can't skew this.
        remaining = max(token.expires_on - time.time(), 0)
        self._token_expires_at = now + remaining - _TOKEN_EXPIRY_SAFETY_MARGIN_SECONDS
        return self._cached_token

    def send(self, *, to: str, subject: str, body: str, correlation_id: str) -> MailResult:
        try:
            access_token = self._get_access_token()
        except Exception as exc:  # noqa: BLE001 - credential resolution failures must not propagate raw
            return MailResult(
                correlation_id=correlation_id, outcome=MailOutcome.FAILED, sent=False,
                error=f"managed identity token acquisition failed: {exc}",
            )

        payload = {
            "message": {
                "subject": subject,
                "body": {"contentType": "Text", "content": body},
                # Sender is always the configured mailbox — sendMail resolves
                # the "from" from the authenticated mailbox context; there is
                # no field here that could override it.
                "toRecipients": [{"emailAddress": {"address": to}}],
            },
            "saveToSentItems": "false",
        }
        try:
            response = httpx.post(
                f"{self._base_url}/users/{self._sender_mailbox}/sendMail",
                headers={"Authorization": f"Bearer {access_token}", "Content-Type": "application/json"},
                json=payload,
                timeout=10.0,
            )
        except httpx.HTTPError as exc:
            return MailResult(
                correlation_id=correlation_id, outcome=MailOutcome.FAILED, sent=False,
                error=f"Graph request failed: {exc}",
            )

        # Optional diagnostic metadata only — never depended on as a
        # business identifier.
        graph_request_id = response.headers.get("request-id") or response.headers.get("client-request-id")

        if response.status_code == 202:
            return MailResult(
                correlation_id=correlation_id, outcome=MailOutcome.SUBMITTED, sent=True,
                graph_request_id=graph_request_id,
            )

        return MailResult(
            correlation_id=correlation_id, outcome=MailOutcome.FAILED, sent=False,
            graph_request_id=graph_request_id,
            error=f"Graph sendMail returned {response.status_code}: {response.text[:500]}",
        )
